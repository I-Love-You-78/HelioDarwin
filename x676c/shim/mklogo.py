#!/usr/bin/env python3
"""Turn a logo image into out/logo.h for the boot splash.

usage: mklogo.py IMAGE OUT.h [HEIGHT]

The image (white logo on a transparent background, any format Pillow
reads) is cropped to its visible pixels and resized to HEIGHT pixels
(default 360) with Lanczos. Its alpha channel becomes a run-length table:
pairs (count 1..255, alpha) row by row. splash.c blends white over black
by that alpha. The image itself stays out of git (x676c/research/).
"""
import sys

from PIL import Image


def main():
    src, out = sys.argv[1], sys.argv[2]
    height = int(sys.argv[3]) if len(sys.argv) > 3 else 360
    im = Image.open(src).convert("RGBA")
    alpha = im.getchannel("A")
    alpha = alpha.crop(alpha.getbbox())
    width = round(alpha.width * height / alpha.height)
    alpha = alpha.resize((width, height), Image.LANCZOS)
    px = alpha.tobytes()

    runs = []
    for y in range(height):
        row = px[y * width:(y + 1) * width]
        x = 0
        while x < width:
            v, n = row[x], 1
            while x + n < width and n < 255 and row[x + n] == v:
                n += 1
            runs += [n, v]
            x += n

    lines = [", ".join(str(b) for b in runs[i:i + 24]) for i in range(0, len(runs), 24)]
    with open(out, "w") as f:
        f.write("/* generated by mklogo.py from %s; do not commit */\n" % src.replace("\\", "/").split("/")[-1])
        f.write("#define LOGO_W %d\n#define LOGO_H %d\n" % (width, height))
        f.write("static const uint8_t logo_rle[] = {\n\t%s,\n};\n" % ",\n\t".join(lines))
    print(f"{out}: {width}x{height}, {len(runs)} bytes RLE")


if __name__ == "__main__":
    main()
